function wiki(file) {
  return `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(file)}?width=900`;
}

function inat(id, ext) {
  return `https://inaturalist-open-data.s3.amazonaws.com/photos/${id}/large.${ext || "jpg"}`;
}

function inatAll(id, ext) {
  return `https://static.inaturalist.org/photos/${id}/large.${ext || "jpg"}`;
}

function wild(item) {
  const name = item.name;
  const short = name.replace(/^Monstera /, "");
  // Photos en plus (galerie.js) : [adresse, crédit, "contain" éventuel]
  const extra = ((window.MONSTERA_GALLERY || {})[item.id] || []).map(([src, credit, fit]) => ({
    src,
    credit,
    fit: fit || "",
  }));
  const main = item.image ? [{ src: item.image, credit: item.credit || "", fit: item.imageFit || "" }] : [];
  const others = extra.filter((p) => p.src !== item.image);
  // mainLast : la photo d’origine est petite, on montre d’abord une photo plus nette.
  const photos = item.mainLast && others.length ? others.concat(main) : main.concat(others);
  const first = photos[0] || {};
  return {
    family: item.family || "Araceae",
    difficulty: item.difficulty || "Peu cultivée",
    light: item.light || "Lumière vive indirecte",
    water: item.water || "Terreau aéré ; le haut doit sécher",
    image: first.src || "",
    imageFit: first.fit || "",
    photos,
    credit: first.credit || item.credit || "Pas de photo libre vérifiée pour cette fiche.",
    size: item.size || "Environ 1–2 m chez toi si elle grimpe ; plusieurs mètres en forêt",
    kind: item.kind || "species",
    common: item.common && item.common.length ? item.common : [short],
    traits: item.traits || ["Espèce acceptée (Kew)"],
    id: item.id,
    name,
    origin: item.origin,
    summary: item.summary,
    description: item.description,
  };
}

function forestNote(where) {
  return `Espèce acceptée par Kew (POWO). ${where} Comme les autres Monsteras, c’est une liane de forêt tropicale : elle germe souvent au sol, cherche un tronc, grimpe, et sa feuille jeune ne ressemble pas toujours à la feuille adulte. On la connaît surtout par les herbiers et les révisions de Croat, Cedeño, Zuluaga, Ortiz et collègues. Rarement en jardinerie : si un vendeur utilise ce nom, demande d’où vient le clone.`;
}

